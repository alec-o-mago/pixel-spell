/**
 * Built-in palette library entries.
 *
 * Entries are starting points: adding one creates a normal editable palette in
 * the workspace. Hardware palettes are factual compatibility color lists;
 * original palettes are released as CC0. Author and legal fields are optional
 * so entries that need neither can leave them blank.
 */
export interface PaletteLibraryEntry {
	id: string;
	name: string;
	colors: string[];
	/** Creator/attribution, when known. */
	author?: string;
	/** License or legal note, when one is needed. */
	legal?: string;
}

